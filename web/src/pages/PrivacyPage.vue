    </ul>
    <p>เราไม่ขายข้อมูลของคุณ ไม่ใช้เพื่อโฆษณา และไม่ทำโปรไฟล์เพื่อการตลาด</p>

    <h2>4. คุกกี้และข้อมูลที่เก็บในเบราว์เซอร์</h2>
    <ul>
      <li><b>คุกกี้เข้าสู่ระบบ (<code>token</code>):</b> มีเฉพาะเมื่อคุณล็อกอิน จำเป็นต่อการทำงานของบัญชี ตั้งเป็น httpOnly (สคริปต์ในหน้าเว็บอ่านไม่ได้) อายุ 30 วัน และถูกลบเมื่อคุณออกจากระบบ</li>
      <li><b>พื้นที่เก็บข้อมูลในเบราว์เซอร์ (localStorage):</b> ธีม ขนาดและแบบตัวอักษร ความกว้างคอลัมน์และระยะบรรทัด อัตราเร็วเสียงอ่าน การเรียงลำดับหน้าแรก ตอนที่อ่านล่าสุด ตำแหน่งที่อ่านค้างและตอนที่อ่านแล้ว ข้อมูลเหล่านี้อยู่ในอุปกรณ์ของคุณ ลบได้โดยล้างข้อมูลเว็บไซต์ในเบราว์เซอร์</li>
      <li>เราไม่ใช้คุกกี้โฆษณาหรือเครื่องมือวิเคราะห์ของบุคคลที่สาม และโฮสต์ตัวอักษรบนเซิร์ฟเวอร์ของเราเอง (ไม่เรียกใช้ Google Fonts) เนื่องจากใช้เฉพาะสิ่งที่จำเป็นต่อการทำงาน จึงไม่มีแบนเนอร์ขอความยินยอมคุกกี้</li>
    </ul>

    <h2>5. การเปิดเผยข้อมูลแก่ผู้อื่น</h2>
    <ul>
