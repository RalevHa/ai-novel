      <li>ที่อยู่ IP ถูกใช้ชั่วคราวในหน่วยความจำของเซิร์ฟเวอร์เพื่อจำกัดการสมัครหรือลองรหัสผ่านถี่ผิดปกติ และไม่ถูกบันทึกลงฐานข้อมูล อย่างไรก็ตาม ระบบโฮสติ้งหรือพร็อกซีที่ให้บริการเว็บไซต์อาจเก็บบันทึกการเข้าถึง (access log) ตามการตั้งค่าของผู้ให้บริการนั้น</li>
