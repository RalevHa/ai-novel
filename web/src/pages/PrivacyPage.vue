      <li><b>ไม่แสดงต่อสาธารณะ:</b> อีเมล รหัสผ่าน เรื่องที่คุณติดตาม ตอนที่คุณอ่าน ตำแหน่งที่อ่านค้าง และการแจ้งเตือน ผู้อื่นไม่เห็นว่าใครโหวตความคิดเห็นใด และผู้เขียนความคิดเห็นไม่ทราบว่าใครรายงาน</li>
      <li><b>ผู้ดูแลระบบ:</b> เห็นรายชื่อสมาชิก อีเมล สิทธิ์ รายงานที่ส่งเข้ามา และบันทึกการจัดการ (เช่น ใครเปลี่ยนสิทธิ์ใคร ใครลบความคิดเห็นของใคร) เพื่อดูแลบริการและความปลอดภัย</li>
    </ul>

    <h2>3. เราใช้ข้อมูลเพื่ออะไร และใช้ฐานทางกฎหมายใด</h2>
