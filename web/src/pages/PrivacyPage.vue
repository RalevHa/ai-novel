      <li><b>ผู้ให้บริการโครงสร้างพื้นฐาน</b> เช่นผู้ให้บริการโฮสติ้งและฐานข้อมูลที่เก็บข้อมูลให้เรา ซึ่งมีหน้าที่รักษาความลับตามสัญญา</li>
      <li><b>หน่วยงานรัฐหรือศาล</b> เมื่อมีกฎหมายหรือคำสั่งที่ชอบด้วยกฎหมายให้เปิดเผย</li>
    </ul>
    <p>เซิร์ฟเวอร์หรือผู้ให้บริการบางรายอาจอยู่นอกประเทศไทย เราจะเลือกผู้ให้บริการที่มีมาตรการคุ้มครองข้อมูลที่เหมาะสม</p>

    <h2>6. เก็บนานแค่ไหน และความปลอดภัย</h2>
    <ul>
      <li>เก็บข้อมูลบัญชีและกิจกรรมของคุณไว้จนกว่าคุณจะขอลบบัญชี บันทึกการจัดการ (ใครทำอะไรกับสิทธิ์และความคิดเห็น) เก็บไว้ตราบเท่าที่จำเป็นต่อความโปร่งใสและความปลอดภัยของการดูแลระบบ</li>
      <li>รหัสผ่านถูกเก็บแบบแฮช คุกกี้เข้าสู่ระบบเป็น httpOnly และเมื่อใช้งานจริงเว็บไซต์ควรทำงานผ่าน HTTPS มีการจำกัดจำนวนครั้งในการล็อกอินและสมัคร อย่างไรก็ตาม ไม่มีระบบใดปลอดภัยสมบูรณ์ หากเกิดเหตุละเมิดข้อมูลที่กระทบคุณ เราจะแจ้งตามที่กฎหมายกำหนด</li>
    </ul>

    <h2>7. สิทธิของคุณ</h2>
    <p>ตาม PDPA คุณมีสิทธิขอเข้าถึงและขอสำเนาข้อมูลของคุณ ขอแก้ไขให้ถูกต้อง ขอลบหรือทำลาย ขอระงับหรือคัดค้านการใช้ ขอให้โอนย้ายข้อมูล และถอนความยินยอมได้ทุกเมื่อ (การถอนไม่กระทบสิ่งที่ทำไปแล้วก่อนถอน)</p>
    <ul>
      <li><b>แก้ไขเอง:</b> เปลี่ยนชื่อที่แสดง คำแนะนำตัว และรหัสผ่านได้ที่หน้า "โปรไฟล์ของฉัน" ลบรีวิวและความคิดเห็นของตัวเองได้ที่รายการนั้น</li>
      <li><b>ขอลบบัญชีหรือใช้สิทธิอื่น:</b> ส่งอีเมลถึงเราตามที่อยู่ท้ายหน้า (ขณะนี้ยังไม่มีปุ่มลบบัญชีในเว็บ) เราจะตอบภายใน 30 วัน เมื่อลบบัญชี ความคิดเห็น รีวิว โหวต เรื่องที่ติดตาม และการแจ้งเตือนของคุณจะถูกลบไปด้วย หากคุณเป็นนักเขียนที่มีเรื่องอยู่ ต้องส่งมอบหรือลบเรื่องเหล่านั้นก่อน</li>
      <li><b>ร้องเรียน:</b> หากเห็นว่าเราไม่ปฏิบัติตามกฎหมาย คุณมีสิทธิร้องเรียนต่อสำนักงานคณะกรรมการคุ้มครองข้อมูลส่วนบุคคล</li>
    </ul>

    <h2>8. เด็กและเยาวชน</h2>
