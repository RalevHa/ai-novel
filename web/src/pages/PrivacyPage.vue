      <li>รักษาความปลอดภัย ป้องกันสแปมและการใช้งานในทางที่ผิด ดูแลเนื้อหา (ประโยชน์โดยชอบด้วยกฎหมายของเรา)</li>
      <li>ดูภาพรวมว่าตอนไหนมีคนอ่านมากเพื่อปรับปรุงบริการ (ใช้ตัวเลขรวมที่ไม่ระบุตัวตน)</li>
